# Build-time converter for OFumo sprite PNG files.

"""Convert an RGBA PNG into XBM-style bitmap and XShape-mask arrays.

Visible dark pixels become foreground bits, visible light pixels become
background bits, and alpha is converted into the XShape mask. Source frames
can be padded onto a common canvas so every runtime sprite has fixed geometry.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

from PIL import Image


def symbol_name(value: str) -> str:
    """Return a C-safe symbol identifier derived from *value*."""
    clean = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if not clean or clean[0].isdigit():
        clean = "sprite_" + clean
    return clean


def pack_bits(rows: list[list[int]], width: int) -> list[int]:
    """Pack rows into XBM LSB-first bytes."""
    out: list[int] = []
    bytes_per_row = (width + 7) // 8
    for row in rows:
        for byte_index in range(bytes_per_row):
            value = 0
            for bit_index in range(8):
                x = byte_index * 8 + bit_index
                if x < width and row[x]:
                    value |= 1 << bit_index
            out.append(value)
    return out


def format_bytes(values: list[int], indent: str = "    ") -> str:
    """Format generated bytes as a compact C initializer."""
    chunks: list[str] = []
    per_line = 12
    for i in range(0, len(values), per_line):
        line = ", ".join(f"0x{value:02x}" for value in values[i : i + per_line])
        chunks.append(indent + line)
    return ",\n".join(chunks)


def main() -> int:
    """Parse arguments, convert the image, and emit the generated header."""
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--symbol", default="sprite")
    parser.add_argument("--width", type=int)
    parser.add_argument("--height", type=int)
    parser.add_argument("--canvas-width", type=int)
    parser.add_argument("--canvas-height", type=int)
    parser.add_argument("--align-x", choices=("left", "center", "right"), default="center")
    parser.add_argument("--align-y", choices=("top", "center", "bottom"), default="bottom")
    parser.add_argument("--threshold", type=int, default=128)
    parser.add_argument("--alpha-threshold", type=int, default=128)
    args = parser.parse_args()

    if not 0 <= args.threshold <= 255:
        parser.error("--threshold must be in range 0..255")
    if not 0 <= args.alpha_threshold <= 255:
        parser.error("--alpha-threshold must be in range 0..255")

    image = Image.open(args.input).convert("RGBA")
    src_width, src_height = image.size

    if args.width is not None and src_width != args.width:
        print(
            f"error: {args.input} is {src_width}x{src_height}; expected width {args.width}",
            file=sys.stderr,
        )
        return 2
    if args.height is not None and src_height != args.height:
        print(
            f"error: {args.input} is {src_width}x{src_height}; expected height {args.height}",
            file=sys.stderr,
        )
        return 2

    width = args.canvas_width if args.canvas_width is not None else src_width
    height = args.canvas_height if args.canvas_height is not None else src_height

    if width < src_width or height < src_height:
        print(
            f"error: canvas {width}x{height} is smaller than source {src_width}x{src_height}",
            file=sys.stderr,
        )
        return 2

    if args.align_x == "left":
        offset_x = 0
    elif args.align_x == "right":
        offset_x = width - src_width
    else:
        offset_x = (width - src_width) // 2

    if args.align_y == "top":
        offset_y = 0
    elif args.align_y == "center":
        offset_y = (height - src_height) // 2
    else:
        offset_y = height - src_height

    canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    canvas.alpha_composite(image, dest=(offset_x, offset_y))

    bitmap_rows: list[list[int]] = []
    mask_rows: list[list[int]] = []

    for y in range(height):
        bitmap_row: list[int] = []
        mask_row: list[int] = []
        for x in range(width):
            red, green, blue, alpha = canvas.getpixel((x, y))
            visible = alpha >= args.alpha_threshold
            luma = (299 * red + 587 * green + 114 * blue) // 1000
            black = visible and luma < args.threshold
            bitmap_row.append(1 if black else 0)
            mask_row.append(1 if visible else 0)
        bitmap_rows.append(bitmap_row)
        mask_rows.append(mask_row)

    bitmap = pack_bits(bitmap_rows, width)
    mask = pack_bits(mask_rows, width)
    symbol = symbol_name(args.symbol).upper()

    header = f"""/* Generated by tools/png_to_xbm.py. Do not edit by hand. */
#ifndef {symbol}_XBM_H
#define {symbol}_XBM_H

#define {symbol}_WIDTH {width}
#define {symbol}_HEIGHT {height}

static const unsigned char {symbol}_BITS[] = {{
{format_bytes(bitmap)}
}};

static const unsigned char {symbol}_MASK_BITS[] = {{
{format_bytes(mask)}
}};

#endif
"""

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
